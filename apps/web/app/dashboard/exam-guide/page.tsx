"use client";
import { useState } from "react";

const API = process.env.NEXT_PUBLIC_API_BASE_URL || "http://localhost:8000";

type ExamGuide = {
  title: string;
  key_topics: string[];
  likely_questions: string[];
  study_tips: string[];
  revision_schedule: Array<{ day: string; focus: string }>;
  time_management_strategy: string;
};

export default function ExamGuidePage() {
  const [subject, setSubject] = useState("Machine Learning & Deep Learning");
  const [examDate, setExamDate] = useState("2026-12-15");
  const [generating, setGenerating] = useState(false);
  const [guide, setGuide] = useState<ExamGuide>({
    title: "Exam Prep Guide: Machine Learning & Deep Learning",
    key_topics: [
      "Supervised vs Unsupervised Learning Paradigms",
      "Gradient Descent & Backpropagation Optimizers (Adam, SGD)",
      "Loss Functions (Cross-Entropy, MSE, Huber)",
      "Regularization: L1 (Lasso), L2 (Ridge), Dropout",
      "Transformers & Attention Mechanisms (Self-Attention, Multi-Head)",
      "Evaluation Metrics: Precision, Recall, F1-Score, ROC-AUC",
    ],
    likely_questions: [
      "Derive the update rule for Gradient Descent and contrast with Stochastic Gradient Descent.",
      "Explain the vanishing gradient problem in deep neural networks and how ReLU/Residual connections mitigate it.",
      "Detail how the Query, Key, and Value vectors interact in the scaled dot-product attention equation.",
      "Compare Bias-Variance tradeoff and explain what techniques reduce high variance.",
    ],
    study_tips: [
      "Master the mathematical derivations on paper first — don't just read code.",
      "Practice drawing neural network architectures and tensor shape transformations.",
      "Use spaced repetition on formulas 48 hours before exam day.",
      "Get at least 7.5 hours of sleep before the exam — cognitive recall drops 20% on sleep deprivation.",
    ],
    revision_schedule: [
      { day: "Day 1 (Core Foundations)", focus: "Linear models, loss functions, optimization math" },
      { day: "Day 2 (Deep Architectures)", focus: "CNNs, RNNs, and Transformer attention blocks" },
      { day: "Day 3 (Applied Problems)", focus: "Practice past exam papers and numerical derivations" },
      { day: "Day 4 (Targeted Fixes)", focus: "Review missed practice questions and memorize key formulas" },
      { day: "Day 5 (Pre-Exam Polish)", focus: "Light high-level review of summary cheat sheets only" },
    ],
    time_management_strategy:
      "Allocate 60% of preparation time to topics with high credit weight (Transformers, Optimization). In the exam hall, spend 10 minutes skimming the entire paper before answering.",
  });

  const handleGenerate = async () => {
    if (!subject.trim()) return;
    setGenerating(true);
    try {
      const res = await fetch(`${API}/api/v1/exam-guide/generate`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ subject, exam_date: examDate }),
      });
      if (res.ok) {
        const data = await res.json();
        if (data.guide) {
          setGuide(data.guide);
        }
      }
    } catch (e) {
      console.error(e);
    }
    setGenerating(false);
  };

  const handleDownload = () => {
    const textContent = `
=====================================================
${guide.title.toUpperCase()}
Exam Date: ${examDate}
Generated by Cortexa AI
=====================================================

--- KEY TOPICS ---
${guide.key_topics.map((t, i) => `${i + 1}. ${t}`).join("\n")}

--- LIKELY EXAM QUESTIONS ---
${guide.likely_questions.map((q, i) => `Q${i + 1}: ${q}`).join("\n\n")}

--- REVISION TIMELINE ---
${guide.revision_schedule.map((s) => `${s.day}: ${s.focus}`).join("\n")}

--- STUDY TIPS ---
${guide.study_tips.map((tip) => `• ${tip}`).join("\n")}

--- TIME MANAGEMENT STRATEGY ---
${guide.time_management_strategy}
`;
    const blob = new Blob([textContent], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `Cortexa_Exam_Guide_${subject.replace(/\s+/g, "_")}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      {/* Title */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-black" style={{ color: "#F0F0FF" }}>
            🎯 Personalized Exam Prep Guide
          </h1>
          <p className="text-sm mt-1" style={{ color: "#64748B" }}>
            AI-generated revision roadmaps, high-yield topics, and realistic practice questions.
          </p>
        </div>
        <button className="btn-cyan text-xs py-2 px-4" onClick={handleDownload}>
          📥 Download Guide (.TXT)
        </button>
      </div>

      {/* Generator settings card */}
      <div className="glass-card p-5">
        <div className="grid md:grid-cols-3 gap-3">
          <div className="md:col-span-2">
            <label className="text-xs font-semibold mb-1 block" style={{ color: "#94A3B8" }}>
              COURSE OR SUBJECT
            </label>
            <input
              className="input-glass"
              placeholder="e.g. Computer Networks, Microeconomics, Organic Chemistry..."
              value={subject}
              onChange={(e) => setSubject(e.target.value)}
            />
          </div>
          <div>
            <label className="text-xs font-semibold mb-1 block" style={{ color: "#94A3B8" }}>
              TARGET EXAM DATE
            </label>
            <input
              type="date"
              className="input-glass"
              value={examDate}
              onChange={(e) => setExamDate(e.target.value)}
            />
          </div>
        </div>
        <div className="mt-4 flex justify-end">
          <button
            className="btn-primary text-xs py-2 px-5"
            onClick={handleGenerate}
            disabled={generating}
          >
            {generating ? "⏳ Formulating Strategy..." : "✨ Generate Strategic Revision Plan"}
          </button>
        </div>
      </div>

      {/* Guide Content Display */}
      <div className="space-y-6">
        {/* Banner with Target Visual */}
        <div
          className="glass-card p-6 flex flex-col md:flex-row items-center justify-between gap-6"
          style={{
            background:
              "linear-gradient(135deg, rgba(139,92,246,0.18), rgba(6,182,212,0.1), rgba(13,17,39,0.95))",
            borderColor: "rgba(139,92,246,0.3)",
          }}
        >
          <div className="space-y-2">
            <span className="badge badge-cyan">STRATEGIC BLUEPRINT</span>
            <h2 className="text-xl font-bold text-white">{guide.title}</h2>
            <p className="text-xs max-w-lg" style={{ color: "#94A3B8" }}>
              {guide.time_management_strategy}
            </p>
          </div>
          <div className="w-24 h-24 rounded-full flex items-center justify-center text-4xl border-2 border-cyan-500/40 bg-cyan-500/10 shadow-[0_0_25px_rgba(6,182,212,0.3)]">
            🎯
          </div>
        </div>

        {/* 2-Column Grid: Key Topics & Likely Questions */}
        <div className="grid md:grid-cols-2 gap-6">
          {/* Key Topics */}
          <div className="glass-card p-5 space-y-3">
            <div className="flex items-center gap-2">
              <span className="text-lg">📌</span>
              <h3 className="text-sm font-bold text-white uppercase tracking-wider">
                High-Yield Key Topics
              </h3>
            </div>
            <ul className="space-y-2 text-sm">
              {guide.key_topics.map((topic, i) => (
                <li
                  key={i}
                  className="flex items-start gap-2 p-2 rounded-lg"
                  style={{ background: "rgba(255,255,255,0.02)" }}
                >
                  <span className="text-cyan-400 font-bold">✓</span>
                  <span style={{ color: "#E0E7FF" }}>{topic}</span>
                </li>
              ))}
            </ul>
          </div>

          {/* Likely Exam Questions */}
          <div className="glass-card p-5 space-y-3">
            <div className="flex items-center gap-2">
              <span className="text-lg">💡</span>
              <h3 className="text-sm font-bold text-white uppercase tracking-wider">
                Likely Practice Questions
              </h3>
            </div>
            <div className="space-y-2 text-xs">
              {guide.likely_questions.map((q, i) => (
                <div
                  key={i}
                  className="p-3 rounded-lg border border-white/5 space-y-1"
                  style={{ background: "rgba(13,17,39,0.7)" }}
                >
                  <span className="badge badge-violet text-[10px]">PRACTICE QUESTION {i + 1}</span>
                  <p className="text-sm font-medium" style={{ color: "#F0F0FF" }}>
                    {q}
                  </p>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Revision Schedule & Tips */}
        <div className="grid md:grid-cols-3 gap-6">
          {/* Schedule */}
          <div className="md:col-span-2 glass-card p-5 space-y-3">
            <div className="flex items-center gap-2">
              <span className="text-lg">📅</span>
              <h3 className="text-sm font-bold text-white uppercase tracking-wider">
                Recommended 5-Day Revision Schedule
              </h3>
            </div>
            <div className="space-y-2">
              {guide.revision_schedule.map((item, idx) => (
                <div
                  key={idx}
                  className="flex items-center justify-between p-3 rounded-lg text-xs"
                  style={{ background: "rgba(255,255,255,0.02)", border: "1px solid rgba(255,255,255,0.05)" }}
                >
                  <span className="font-bold text-violet-400">{item.day}</span>
                  <span style={{ color: "#94A3B8" }}>{item.focus}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Tips */}
          <div className="glass-card p-5 space-y-3">
            <div className="flex items-center gap-2">
              <span className="text-lg">🧠</span>
              <h3 className="text-sm font-bold text-white uppercase tracking-wider">
                High-Recall Tips
              </h3>
            </div>
            <div className="space-y-2 text-xs" style={{ color: "#94A3B8" }}>
              {guide.study_tips.map((tip, i) => (
                <div key={i} className="flex items-start gap-2">
                  <span className="text-yellow-400">⚡</span>
                  <span>{tip}</span>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
